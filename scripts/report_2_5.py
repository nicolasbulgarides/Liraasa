"""report_2_5.py: write review/changelog_2_5.md and review/resolution_report_2_5.md.

    PYTHONUTF8=1 python scripts/report_2_5.py

Both are read from the record, not written beside it: the author's patch
(data/proposals/liraasa_2_5_patch.json), the three 2.5 changesets
(data/changes/2026-10-22-lexicon-2-5*.json), the 2.3 audit's issue list
(review/grammar_spec_2_3.md) and the measured diagnosis
(review/translator_diagnosis_2_5.data.json).
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = lambda *p: os.path.join(ROOT, *p)


def load(*p):
    with open(J(*p), encoding="utf-8") as f:
        return json.load(f)


patch = load("data", "proposals", "liraasa_2_5_patch.json")
steps = [load("data", "changes", f) for f in ("2026-10-22-lexicon-2-5-album.json", "2026-10-22-lexicon-2-5.json", "2026-10-22-lexicon-2-5-housekeeping.json")]
diag = load("review", "translator_diagnosis_2_5.data.json")["summary"]
with open(J("review", "grammar_spec_2_3.md"), encoding="utf-8") as f:
    audit = f.read()
issues = re.findall(r"^### (I-\d+) — (.+)$", audit, re.M)

ops = [o for cs in steps for o in cs["ops"]]
rulings = {r["id"]: r for cs in steps for r in cs.get("rulings", [])}


def by(op):
    return [o for o in ops if o["op"] == op]


# ------------------------------------------------------------- changelog
out = ["# Liraasa 2.5: changelog", "",
       "Generated by `PYTHONUTF8=1 python scripts/report_2_5.py` from the author's patch and the three 2.5 changesets. 2.5 is a grammar release built from frozen 2.3 (`npm run integrate:2.5`); no root is respelled, and the one new word is `antizi`.", "",
       "## New rulings", "", "| Ruling | Issue | Topic | Summary |", "| --- | --- | --- | --- |"]
for d in patch["decisions"]:
    if d["ruling_id"] is None:
        continue
    rid = d["ruling_id"].split(":")[1]
    r = rulings[rid]
    summary = d["text"].split(". ")[0].rstrip(".") + "."
    out.append(f"| {d['ruling_id']} | {d['issue']} | {r['topic']} | {summary.replace('|', '/')} |")
out += ["", "Rulings 2.5:G126–G128 stand in their topic's place in the patch (after G89 and G93), as the patch orders them; their ids come last so no earlier id changed.", "",
        "## Superseded rulings (kept as ruled, marked `superseded_by` / `superseded_in_part`)", ""]
for o in by("supersede_ruling"):
    out.append(f"- {o['entry']} ({o['from']}){' — the part: ' + o['field'] if o.get('field') else ''} → {o['to']}")
out += ["", "## Amended rulings (kept as ruled, marked `amended_by`; where they differ, the 2.5 ruling is followed)", ""]
for o in by("amend_ruling"):
    out.append(f"- {o['entry']} ({o['from']}) → {o['to']}: {o.get('field', '')}")
for o in by("mark_ruling_covered"):
    out.append(f"- {o['entry']} ({o['from']}) is covered by {o['to']} (`covered_by`); it still stands")
out += ["", "## Examples changed", "", "| Example | Before | After | Why |", "| --- | --- | --- | --- |"]
for o in by("edit_example"):
    out.append(f"| {o['entry']}{' (English)' if o.get('field') == 'english' else ''} | `{o['from']}` | `{o['to']}` | {o['reason'].replace('|', '/')} |")
out += ["", "## Texts archived to `legacy.archived_text`", ""]
for o in by("archive_text"):
    out.append(f"- {o['entry']} {o.get('field', '')}: `{o['from']}` → `{o['to']}` ({o['reason']})")
out += ["", "## Function-word rows rewritten", ""]
for o in by("edit_function_word"):
    out.append(f"- {o['entry']} {o['field']}: “{o['from']}” → “{o['to']}”")
for o in by("add_function_word"):
    out.append(f"- added {o['to']} ({o['entry']}): {o['reason']}")
out += ["", "## Grammar texts and values", ""]
for o in by("edit_text"):
    out.append(f"- {o['entry']}: “{o['from']}” → “{o['to']}”")
seen_kind = 0
for o in by("edit_value"):
    if ".kind" in o["entry"] or ".time_class" in o["entry"]:
        seen_kind += 1
        continue
    out.append(f"- {o['entry']}: {o['reason']}")
out.append(f"- {seen_kind} rows classed: every live example's `kind` that is not a canonical sentence (I-40), every time-table row's `time_class` (I-27)")
for o in by("edit_metadata"):
    out.append(f"- {o['entry']}: {o['to']} declared ({o['reason']})")
out += ["", "## Housekeeping done", ""]
for h in patch["housekeeping"]["items"]:
    out.append(f"- {h['issue']}: {h['action']}")
out += ["", "## Summaries the build scripts write", "",
        "`hard_rules`, `clause` (`explanation`, `copulas`, `questions`, `commands`, `linking`, new `edges`), `recipes`, `self_check`, `how_to_translate`, `open_questions_do_not_resolve`, `small_words` (the time-word split, the historical and formulae table, bound correlative bases) and `examples` (canonical sentences, word-building illustrations, contrasts to avoid) are written by `scripts/build_llm_json.ts` and `scripts/grammar_guide/chapters.ts`; they now restate the 2.5 rulings and no superseded rule. The album section says it is non-normative (2.5:G87).", ""]
with open(J("review", "changelog_2_5.md"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out) + "\n")

# ------------------------------------------------------ resolution report
issue_rulings = {}
for d in patch["decisions"]:
    for i in re.findall(r"I-\d+", d["issue"]):
        issue_rulings.setdefault(i, []).append(d["ruling_id"] or "no grammar change")
for item in patch["housekeeping"]["items"]:
    issue_rulings.setdefault(item["issue"], []).append("housekeeping")
need = {}
for a in patch["author_inputs_needed"]:
    for i in re.findall(r"I-\d+", a["item"]):
        need.setdefault(i, []).append(a["question"])
out = ["# Liraasa 2.5: resolution report", "",
       "Generated by `PYTHONUTF8=1 python scripts/report_2_5.py`. Each issue of the 2.3 audit (review/grammar_spec_2_3.md) with what 2.5 did about it. RESOLVED means the author ruled and the ruling is in 2.5; NEEDS AUTHOR INPUT means part of it is in `review/questions_2_5.md`.", "",
       "| Issue | Status | By | Still open |", "| --- | --- | --- | --- |"]
for iid, title in issues:
    by_ = issue_rulings.get(iid, [])
    open_ = need.get(iid, [])
    status = "RESOLVED" if by_ and not open_ else ("RESOLVED in part; NEEDS AUTHOR INPUT" if by_ else ("NEEDS AUTHOR INPUT" if open_ else "DEFERRED"))
    out.append(f"| {iid} {title.replace('|', '/')} | {status} | {', '.join(dict.fromkeys(by_)) or '—'} | {' / '.join(open_) or '—'} |")
out += ["", "## Derived entries, for the author to confirm", "",
        "The patch marks these as consequences it had to spell out. They are applied, and each is listed in review/questions_2_5.md.", ""]
for d in patch["decisions"]:
    for x in d.get("derived", []):
        out.append(f"- {d['ruling_id']} ({d['issue']}): {x}")
out += ["", "## Tests", "",
        "| | Before (the 2.3 tools on the 2.5 sets) | After (2.5) |", "| --- | --- | --- |",
        f"| Golden: the patch's ✓ examples read clean | {diag['patch_good']['total'] - diag['patch_good']['old_flags']} of {diag['patch_good']['total']} | 104 of 104 |",
        "| Golden: canonical sentences, recipes and living ruling examples read clean | (not run against 2.5) | 708 of 717 lines; the 9 others are pinned findings for the author |",
        f"| Negative: the patch's ✗ examples rejected | {diag['patch_bad']['total'] - diag['patch_bad']['old_accepts']} of 20 (0 citing the right rule) | 20 of 20, each citing its ruling |",
        f"| Negative: album lines rejected (2.5:G87: the album is not canon) | {diag['album']['old_flags']} of {diag['album']['lines']} | 47 of 275, pinned; every adjective-for-noun or form-for-slot line among them |",
        f"| English → Liraasa: the patch's ✓ examples from their English | {diag['translate']['old_passes_2_5_checker']} of {diag['translate']['total']} pass the 2.5 checker ({diag['translate']['old_exact']} exactly as the patch) | {diag['translate']['new_ok']} of {diag['translate']['total']} ({diag['translate']['new_exact']} exactly as the patch; the one left has no listed word, and says so) |",
        "| English → Liraasa: the 106 cases of tests/translate/cases_2_5.json | — | 106 of 106 (10 marked for review) |",
        "| Round trip: a golden sentence parses to a frame and regenerates to itself | — (no frame existed) | 744 of 752 sentences; the 8 others are asides (, hema, / , nido,) and quotations the frame does not carry yet |",
        "| The whole suite, `npm run check` | 681 tests | 929 tests, all passing |", ""]
with open(J("review", "resolution_report_2_5.md"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out) + "\n")
print("wrote review/changelog_2_5.md and review/resolution_report_2_5.md")
