/**
 * Build what the songbook editor loads for the 2.5 strict checker and the
 * translator (ADR-0020):
 *
 *   editor/grammar/grammar-core.js   src/core/grammar + src/core/translate as one
 *                                    classic script, window.LiraasaGrammar
 *   editor/grammar/grammar-data.js   window.LIRAASA_GRAMMAR: the translator's
 *                                    sources (the 2.5 reference, the checker's
 *                                    overlay and rule parameters, the English
 *                                    data, the numerals and synonyms)
 *
 *   npm run build:grammar   (after build:llm)
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath, URL } from 'node:url';
import { build } from 'vite';
import { loadTranslateSource } from './grammar_source';

const OUT_DIR = 'editor/grammar';

async function main(): Promise<void> {
  await build({
    configFile: false,
    logLevel: 'warn',
    build: {
      outDir: OUT_DIR,
      emptyOutDir: false,
      minify: false,
      sourcemap: false,
      target: 'es2020',
      lib: {
        entry: fileURLToPath(new URL('../src/core/translate/bundle.ts', import.meta.url)),
        name: 'LiraasaGrammar',
        formats: ['iife'],
        fileName: () => 'grammar-core.js',
      },
    },
  });
  mkdirSync(OUT_DIR, { recursive: true });
  const src = loadTranslateSource();
  writeFileSync(
    `${OUT_DIR}/grammar-data.js`,
    `/* Generated by scripts/build_grammar_bundle.ts. Do not edit. */\nwindow.LIRAASA_GRAMMAR = ${JSON.stringify(src)};\n`,
    'utf8',
  );
  console.log(`grammar-core.js and grammar-data.js → ${OUT_DIR}/`);
}

void main();
