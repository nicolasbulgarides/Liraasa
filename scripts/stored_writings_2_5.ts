/**
 * CLI: run the 2.5 strict checker over every stored Liraasa text and write
 * review/stored_writings_2_5.md (README 2f). Grammar is never auto-corrected:
 * a grammar fix changes meaning and needs the author.
 *
 *   npx tsx scripts/stored_writings_2_5.ts
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createChecker, type LineResult } from '../src/core/grammar';
import { loadGrammarSource } from './grammar_source';

const ck = createChecker(loadGrammarSource());
interface Source {
  name: string;
  path: string;
  lines: string[];
}
const textFile = (path: string): string[] =>
  readFileSync(path, 'utf8')
    .replace(/^\uFEFF/, '')
    .split(/\r?\n/)
    // English is on "# EN:" lines (the corpus) or indented under its line (the songs)
    .filter((l) => !/^\s/.test(l))
    .map((l) => l.trim())
    .filter((l) => l !== '' && !l.startsWith('#') && /[a-z]/.test(l));
const sources: Source[] = [];
for (const f of readdirSync('data/corpus/songs_2_3')
  .filter((x) => x.endsWith('.txt'))
  .sort())
  sources.push({
    name: `Song: ${f}`,
    path: `data/corpus/songs_2_3/${f}`,
    lines: textFile(join('data/corpus/songs_2_3', f)),
  });
sources.push({
  name: 'Bumrepago (the bakery story)',
  path: 'data/corpus/bumrepago_2_3/bumrepago.txt',
  lines: textFile('data/corpus/bumrepago_2_3/bumrepago.txt'),
});
sources.push({
  name: 'Nemelira de devi (the song the guide reads)',
  path: 'data/songs/Nemelira de devi.txt',
  lines: textFile('data/songs/Nemelira de devi.txt').slice(1) /* the first line is its title */,
});
const myth = JSON.parse(readFileSync('tests/audit/myth.json', 'utf8')) as {
  sentences: { spec?: string }[];
};
sources.push({
  name: 'The Goddess and the Singer (the audit myth, hand translation)',
  path: 'tests/audit/myth.json',
  lines: myth.sentences.map((s) => s.spec ?? '').filter((l) => l !== ''),
});
const page = readFileSync('editor/index.html', 'utf8');
const sample = /const SAMPLE = \[([\s\S]*?)\]\.join/.exec(page)?.[1] ?? '';
sources.push({
  name: "The editor's seed piece (SAMPLE)",
  path: 'editor/index.html',
  lines: [...sample.matchAll(/'([^']*)'/g)].map((m) => m[1] ?? '').filter((l) => l !== ''),
});
const album = JSON.parse(readFileSync('data/corpus/album_2_0/album_current.json', 'utf8')) as {
  songs: {
    track: string;
    title: string;
    lines: { n: number; recorded: string; current: string | null }[];
  }[];
};
for (const s of album.songs)
  sources.push({
    name: `Album ${s.track}: ${s.title} (non-normative, 2.5:G87)`,
    path: 'data/corpus/album_2_0/album_current.json',
    lines: s.lines.map((l) => l.current ?? l.recorded),
  });

const out: string[] = [
  '# Stored writings under the 2.5 grammar',
  '',
  "Generated by `npx tsx scripts/stored_writings_2_5.ts`. Every stored Liraasa text in the repository, read by the 2.5 strict checker (src/core/grammar). Nothing here is auto-corrected: a grammar fix changes meaning and needs the author. Respellings are not grammar; the root viewer's auto-correct covers them.",
  '',
  "Not covered here: the pieces saved in the songbook editor live in each browser's storage, which the repository cannot read. The editor re-checks a piece with the 2.5 checker every time it is opened, so they show their findings there.",
  '',
  '| Text | Lines | Lines with an error | with a warning only | unruled notes |',
  '| --- | ---: | ---: | ---: | ---: |',
];
const detail: string[] = [];
let totalLines = 0;
let totalErr = 0;
const byRule = new Map<string, number>();
for (const s of sources) {
  const results: { line: string; r: LineResult }[] = s.lines.map((line) => ({
    line,
    r: ck.checkLine(line),
  }));
  const err = results.filter((x) => x.r.findings.some((f) => f.severity === 'error'));
  const warn = results.filter(
    (x) =>
      !x.r.findings.some((f) => f.severity === 'error') &&
      x.r.findings.some((f) => f.severity === 'warn'),
  );
  const unruled = results.filter((x) => x.r.findings.some((f) => f.severity === 'unruled'));
  totalLines += results.length;
  totalErr += err.length;
  out.push(
    `| ${s.name} | ${String(results.length)} | ${String(err.length)} | ${String(warn.length)} | ${String(unruled.length)} |`,
  );
  const bad = results.filter((x) => x.r.findings.some((f) => f.severity !== 'note'));
  if (bad.length === 0) continue;
  detail.push(`## ${s.name}`, '', `\`${s.path}\``, '');
  for (const { line, r } of bad) {
    detail.push(`- \`${line}\``);
    for (const f of r.findings.filter((x) => x.severity !== 'note')) {
      byRule.set(f.rule, (byRule.get(f.rule) ?? 0) + 1);
      detail.push(
        `  - **${f.severity}** ${f.rule}: ${f.message}${f.fix === undefined ? '' : ` (try: ${f.fix})`}`,
      );
    }
  }
  detail.push('');
}
out.push(
  '',
  `${String(totalLines)} lines in all; ${String(totalErr)} with at least one error.`,
  '',
  '## Findings by rule',
  '',
  '| Rule | Findings |',
  '| --- | ---: |',
);
for (const [rule, n] of [...byRule].sort((a, b) => b[1] - a[1]))
  out.push(`| ${rule} | ${String(n)} |`);
out.push('', ...detail);
writeFileSync('review/stored_writings_2_5.md', `${out.join('\n')}\n`, 'utf8');
console.log(
  `wrote review/stored_writings_2_5.md: ${String(totalLines)} lines, ${String(totalErr)} with errors`,
);
