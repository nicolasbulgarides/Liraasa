/**
 * The learning module's curriculum and gap report: what the skill graph
 * teaches in what order, and every gap the author should look at.
 *
 *   npm run learn:report                 → review/learn_report.md
 *   npm run learn:report -- --out FILE
 */
import { writeFileSync } from 'node:fs';
import {
  EMPTY_OVERRIDES,
  buildLearnSource,
  buildSkillGraph,
  candidateExamples,
  type LinkContext,
  validateCurriculum,
  type Gap,
  type LearnData,
  type SkillGraph,
} from '../src/core/learn';
import { parseArgs } from './args';
import { loadLearnInput } from './learn_inputs';

const OUT = 'review/learn_report.md';

function label(data: LearnData, graph: SkillGraph, id: string): string {
  const node = graph.nodes.get(id);
  if (node === undefined) return id;
  if (node.kind === 'concept') return data.concepts.get(node.ref)?.title ?? id;
  const item = data.items.get(node.ref);
  const name = item === undefined ? id : `${item.spelling} (${item.meaning})`;
  return node.kind === 'pattern' ? `compounds on ${name}` : name;
}

function candidates(data: LearnData, context: LinkContext, gaps: readonly Gap[]): string[] {
  const out = [
    '## Candidate examples for rulings without sentences',
    '',
    'Existing sentences that use the words each ruling names. Confirm the ones that',
    'truly illustrate it by copying their keys into `rulingExamples` in',
    '`data/lessons/overrides.json`; the ruling then gets exercises.',
    '',
  ];
  let covered = 0;
  const missing = gaps.filter((g) => g.code === 'concept-no-examples' && g.ref.startsWith('rule:'));
  for (const g of missing) {
    const ref = g.ref.slice('rule:'.length);
    const list = candidateExamples(data, context, ref);
    out.push(`### ${data.concepts.get(g.ref)?.title ?? ref}`, '');
    if (list.length === 0) {
      out.push('- no sentence uses the words this ruling names: it needs a new example', '');
      continue;
    }
    covered += 1;
    for (const c of list) {
      out.push(`- \`${c.example.key}\` ${c.example.liraasa} — ${c.example.english ?? ''}`);
    }
    out.push('');
  }
  out.splice(6, 0, `${String(covered)} of ${String(missing.length)} rulings have candidates.`, '');
  return out;
}

function report(
  data: LearnData,
  context: LinkContext,
  graph: SkillGraph,
  gaps: readonly Gap[],
): string {
  const out: string[] = [];
  const count = (sev: string): number => gaps.filter((g) => g.severity === sev).length;
  const roots = [...graph.nodes.values()].filter((n) => n.kind === 'root');
  out.push(
    `# Learning module: curriculum and gaps (${data.edition})`,
    '',
    'Generated by `npm run learn:report` from the lexicon, the validated corpus and',
    '`data/lessons/overrides.json`. Nothing here is canon: it is what the learning',
    'module derives, and what it could not derive.',
    '',
    '## Summary',
    '',
    `- ${String(data.items.size)} items, ${String(data.concepts.size)} grammar concepts, ${String(data.examples.length)} sentences, ${String(data.texts.length)} texts`,
    `- ${String(graph.nodes.size)} skill-graph nodes in ${String(graph.units.length)} units; ${String(roots.filter((n) => n.level === 'core').length)} core roots, ${String(roots.filter((n) => n.level === 'advanced').length)} advanced (in no sentence)`,
    `- gaps: ${String(count('error'))} errors, ${String(count('warn'))} warnings, ${String(count('note'))} notes`,
    '',
    '## The first 20 units',
    '',
  );
  for (const u of graph.units.slice(0, 20)) {
    out.push(
      `${String(u.index + 1)}. **${u.theme ?? '—'}**: ${u.nodes.map((n) => label(data, graph, n)).join(' · ')}`,
    );
  }
  out.push('', '## Grammar concepts, in teaching order', '');
  for (const id of graph.order.filter((n) => n.startsWith('concept:'))) {
    const node = graph.nodes.get(id);
    out.push(`- unit ${String((node?.unit ?? 0) + 1)}: ${label(data, graph, id)}`);
  }

  out.push('', ...candidates(data, context, gaps));

  const groups = new Map<string, Gap[]>();
  for (const g of gaps) groups.set(g.code, [...(groups.get(g.code) ?? []), g]);
  out.push('', '## Gaps', '');
  for (const sev of ['error', 'warn', 'note'] as const) {
    for (const [code, list] of groups) {
      if (list[0]?.severity !== sev) continue;
      out.push(`### ${sev}: ${code} (${String(list.length)})`, '');
      const shown = code === 'root-no-examples' ? list.slice(0, 60) : list;
      for (const g of shown) out.push(`- \`${g.ref}\`: ${g.message}`);
      if (shown.length < list.length)
        out.push(`- … and ${String(list.length - shown.length)} more`);
      out.push('');
    }
  }
  return out.join('\n');
}

function main(): void {
  const { flags } = parseArgs(process.argv.slice(2), ['out']);
  const input = loadLearnInput();
  const overrides = input.overrides ?? EMPTY_OVERRIDES;
  const { data, context } = buildLearnSource(input);
  const graph = buildSkillGraph(data, overrides);
  const gaps = validateCurriculum(data, graph, overrides);
  const out = flags.out ?? OUT;
  writeFileSync(out, report(data, context, graph, gaps) + '\n', 'utf8');
  const errors = gaps.filter((g) => g.severity === 'error').length;
  console.log(
    `${String(graph.units.length)} units, ${String(gaps.length)} gaps (${String(errors)} errors) → ${out}`,
  );
  if (errors > 0) process.exitCode = 1;
}

main();
