"""questions_2_5.py: write review/questions_2_5.md, the author's fill-in list for 2.5.

    PYTHONUTF8=1 python scripts/questions_2_5.py

Read from the record: the patch's author_inputs_needed and derived entries,
the drafts (data/checker/drafts_2_5.json), the one-edit pairs the position
check found competing, the canon the strict checker rejects
(tests/grammar/fixtures/known_findings_2_5.json) and the translator cases
marked for review (tests/translate/cases_2_5.json).
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = lambda *p: os.path.join(ROOT, *p)


def load(*p):
    with open(J(*p), encoding="utf-8") as f:
        return json.load(f)


patch = load("data", "proposals", "liraasa_2_5_patch.json")
drafts = load("data", "checker", "drafts_2_5.json")
known = load("tests", "grammar", "fixtures", "known_findings_2_5.json")
cases = load("tests", "translate", "cases_2_5.json")["cases"]
with open(J("scripts", "make_changeset_2_5.ts"), encoding="utf-8") as f:
    gen = f.read()
pairs = re.findall(r"\{\s*pair: \['([a-z]+)', '([a-z]+)'\],\s*competes: (true|false),\s*why:\s*'([^']*)',?\s*\}", gen)

by_issue = {}
for d in patch["decisions"]:
    for i in re.findall(r"I-\d+", d["issue"]):
        by_issue.setdefault(i, []).append(d)


def examples(issue):
    out = []
    for d in by_issue.get(issue, []):
        for e in d.get("examples_grammatical", []):
            out.append(f"  - ✓ `{e['liraasa']}` {e.get('english', '')} ({d['ruling_id']})")
        for e in d.get("examples_ungrammatical", []):
            out.append(f"  - ✗ `{e['liraasa']}` ({e.get('why', '')}; {d['ruling_id']})")
    return out


out = ["# Liraasa 2.5: questions for the author", "",
       "Generated by `PYTHONUTF8=1 python scripts/questions_2_5.py`. Fill in the **Answer** lines. Nothing here is applied until you answer; until then the strict checker reports what depends on it as `unruled`, never pass or fail.", "",
       "## 1. The patch's open questions (author_inputs_needed)", ""]
for n, a in enumerate(patch["author_inputs_needed"], 1):
    out.append(f"### 1.{n}. {a['item']}")
    out.append("")
    out.append(a["question"])
    out.append("")
    for i in re.findall(r"I-\d+", a["item"]):
        out += examples(i)
    if a["item"].startswith("I-22"):
        out.append("  - The draft is in section 2.1 below.")
    if a["item"].startswith("I-38"):
        out.append("  - The draft is in section 2.2 below.")
    out += ["", "**Answer:**", ""]

out += ["## 2. Drafts for approval", "",
        "**These are drafts.** They are found by verb gloss (scripts/build_grammar_data.ts) and are not treated as final: the checker reports a construction that depends on them as `unruled`. Strike what does not belong and add what is missing.", "",
        "### 2.1. Change-of-state verbs (2.5:G110, I-22): the subject may be the thing that changes", "",
        "The patch asks that lallela and momvima be in the list. Without gome, these verbs' subject may be the thing that changes (an anticausative: Zafra, li dorbi po lallela).", ""]
for v, g in sorted(drafts["change_of_state_verbs"]["verbs"].items()):
    out.append(f"- [ ] `{v}`: {g}")
out += ["", "**Answer:**", "",
        "### 2.2. Verbs whose meaning has a recipient (2.5:G112, I-38): a pronoun recipient may stand bare after them", "",
        "Already approved for 1.2:G26 (give-type, data/checker/lexicon_flags.json): " + ", ".join(f"`{v}`" for v in drafts["recipient_verbs"]["approved_already"]) + ".", "", "Drafted:", ""]
for v, g in sorted(drafts["recipient_verbs"]["verbs"].items()):
    out.append(f"- [ ] `{v}`: {g}")
out += ["", "**Answer:**", "", "## 3. Derived entries to confirm", "",
        "The patch spelled these out to make your choice unambiguous. They are applied; confirm or correct each.", ""]
for d in patch["decisions"]:
    for x in d.get("derived", []):
        out += [f"- **{d['ruling_id']}** ({d['issue']}): {x}", "  **Answer:**", ""]

out += ["## 4. Conflicts found while applying the patch", "",
        "The README asks me to stop and ask when an edit would change more than the patch describes, or a ✓ example fails. None of the patch's examples fails. These are the places where the patch and the rest of the data meet; nothing below was changed.", "",
        "1. **Amended rulings and 2.3:G84.** 2.3:G84 says what a *superseded* ruling allowed stays grammatical. The patch *amends* (does not supersede) 2.2:G60, and rejects `Taivo pagopa ki-pago?`, which G60 allowed. The checker follows the patch: an amended ruling's old licence does not survive where the new ruling differs. Is that right, or should G84 cover amended rulings too?", "   **Answer:**", "",
        "2. **`pilo de bumre` in living text.** Under 2.5:G95 `pilo de bumre` is \"the father of the bread\", not \"father's bread\". The patch rewrote recipes[20]; two other places still use it for \"father's bread\": 1.2:G27's example 2 (`Eli bumre ka sambasan ko pilo de bumre.`, a ruling, never reworded) and the recipe \"the same as / different from\" (the same sentence). They now read grammatically, with the other meaning. Archive 1.2:G27's example and rewrite the recipe as `… ko li bumre de pilo`?", "   **Answer:**", "",
        "3. **`una-de-dossa`.** 2.5:G97 says fractions are never hyphenated; the word-building illustration `una-de-dossa; tressa de cuara` (examples, now an illustration) still writes one. Rewrite it as `una de dossa`?", "   **Answer:**", "",
        "4. **0.8:R9's wording (I-41).** The housekeeping asks that seye, mufe, poye, pifu, zoke be called ATTITUDE words everywhere, \"0.8:R9 wording\" included. The function-word rows and the slot are done; 0.8:R9 is a ruling, and rulings are never reworded. Leave it, or supersede its wording with a new ruling?", "   **Answer:**", "",
        "5. **A FRAME's comma.** 2.5:G127 defines FRAME as \"set off by a comma\"; 1.2:G24 (now amended) made the comma optional, and canon writes `Eli-krono maivo lirala.` The checker warns (it does not reject) on a FRAME without its comma. Is the comma required?", "   **Answer:**", "",
        "6. **A time word between the subject and the verb.** 2.5:G126 has no slot for it (FRAME or the adjuncts). Canon has `Maivo nuna-krono lirala.`; the checker now rejects it, citing 2.5:G126. Rule it in, or rewrite the example?", "   **Answer:**", "",
        "7. **The duplicate time-table rows (I-27).** The housekeeping says to remove the duplicate eli-krono, toda-krono, nuna-krono rows. They are marked `time_class: duplicate` and left out of the reference, not deleted from the lexicon (they have ids). Delete them outright?", "   **Answer:**", "",
        "8. **gome and attestation (2.5:G110).** `sevresia` (close) is not attested with an object anywhere in the data, so the canonical `Li dorbi gome sevresia gagu li sora.` now warns. Attest it (an example with an object), or treat the function word's own example as attestation?", "   **Answer:**", "",
        "9. **`ke sidu`** (\"destined to\") stays an open question; the album uses it (AR-10). The checker reports it as `unruled`.", "", ]

out += ["## 5. The one-edit pairs that compete (I-34)", "",
        "The patch says to declare a pair only if a position check shows the two never compete for one slot. Declared in 2.5: " + ", ".join(f"{a}/{b}" for a, b, c, _ in pairs if c == "false") + ". These compete, li/la first, and are left undeclared for you:", ""]
for a, b, c, why in pairs:
    if c == "true":
        out += [f"- **{a}/{b}**: {why}", "  **Answer:**"]
out += ["", "## 6. Canon the 2.5 checker rejects", "",
        "Canonical sentences, recipes and living ruling examples that fail or warn under 2.5 (pinned in tests/grammar/fixtures/known_findings_2_5.json). Rewrite, or rule them in.", ""]
for k, v in known["canon"].items():
    out += [f"- `{k}` — {', '.join(v)}", "  **Answer:**"]
out += ["", "## 7. Translator expectations to confirm", "",
        "English → Liraasa cases (tests/translate/cases_2_5.json) where the translator's choice is a reasonable reading but not the patch's own wording. The test accepts both; tell me which the translator should prefer.", ""]
for c in cases:
    if "review" in c:
        out += [f"- {c['english']} → `{c['expect']}`" + (f" (also accepted: {', '.join('`' + e + '`' for e in c.get('equivalents', []))})" if c.get("equivalents") else ""), f"  - {c['review']}", "  **Answer:**"]
out.append("")
with open(J("review", "questions_2_5.md"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out) + "\n")
print("wrote review/questions_2_5.md")
