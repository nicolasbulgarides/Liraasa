/**
 * Build what the songbook editor's Learn view loads (ADR-0015):
 *
 *   editor/learn/learn-core.js   src/core/learn bundled as one classic script,
 *                                window.LiraasaLearn, so the editor still
 *                                opens from file:// with no module loader
 *   editor/learn/learn-data.js   window.LIRAASA_LEARN: the lexicon, the
 *                                validated corpus, the names, the author's
 *                                overrides, and the previous edition's
 *                                snapshot for the "What changed" lesson,
 *                                and the audio files that exist (D9)
 *
 *   npm run build:learn
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, URL } from 'node:url';
import { build } from 'vite';
import { AUDIO_DIR, buildLearnData, readAudioManifest, snapshotEdition } from '../src/core/learn';
import type { IdMapFile } from '../src/core/model/ids';
import type { RawLexicon } from '../src/core/model/raw';
import { loadLearnInput } from './learn_inputs';
import { INTRO, MAP, OPEN, PARTS } from './lessons/lessons_3_0';

/** The edition before the current one, for the "What changed" lesson. */
const PREVIOUS = 'data/lexicon/liraasa_4_0.json';
const IDS = 'data/lexicon/ids.json';
const AUDIO_MANIFEST = `${AUDIO_DIR}/manifest.json`;

const OUT_DIR = 'editor/learn';

async function main(): Promise<void> {
  await build({
    configFile: false,
    logLevel: 'warn',
    resolve: {
      alias: { '@core': fileURLToPath(new URL('../src/core', import.meta.url)) },
    },
    build: {
      outDir: OUT_DIR,
      emptyOutDir: false,
      minify: false,
      sourcemap: false,
      target: 'es2020',
      lib: {
        entry: fileURLToPath(new URL('../src/core/learn/index.ts', import.meta.url)),
        name: 'LiraasaLearn',
        formats: ['iife'],
        fileName: () => 'learn-core.js',
      },
    },
  });

  const input = loadLearnInput();
  // 1.1 carries no inline ids: read it through the sidecar, as the 1.2 build did
  const previous = snapshotEdition(
    buildLearnData({
      lexicon: JSON.parse(readFileSync(PREVIOUS, 'utf8')) as RawLexicon,
      ids: JSON.parse(readFileSync(IDS, 'utf8')) as IdMapFile,
      // read with the same glosses as the current edition, so only real changes differ
      ...(input.pronounEnglish !== undefined ? { pronounEnglish: input.pronounEnglish } : {}),
    }),
  );
  // the recordings listed in the manifest whose file is really there
  const manifest = readAudioManifest(
    existsSync(AUDIO_MANIFEST) ? JSON.parse(readFileSync(AUDIO_MANIFEST, 'utf8')) : undefined,
    buildLearnData(input),
  );
  const audioFiles = Object.fromEntries(
    Object.entries(manifest.files).filter(([, path]) => existsSync(`${AUDIO_DIR}/${path}`)),
  );
  const absent = Object.keys(manifest.files).filter((k) => !(k in audioFiles));
  for (const [label, keys] of [
    ['names no word or sentence', manifest.unknownKeys],
    ['has a path outside data/audio', manifest.badPaths],
    ['lists a file that does not exist', absent],
  ] as const) {
    if (keys.length > 0) console.warn(`audio manifest ${label}: ${keys.join(', ')}`);
  }

  const payload = {
    lexicon: input.lexicon,
    corpus: input.corpus,
    names: input.names,
    overrides: input.overrides,
    pronounEnglish: input.pronounEnglish,
    previous,
    audioFiles,
    // The Grammar in Lessons, checked by npm run build:lessons (scripts/lessons/)
    course: { edition: '4.1', intro: INTRO, parts: PARTS, map: MAP, open: OPEN },
  };
  const js =
    '/* Generated by npm run build:learn. Do not edit: edit the lexicon, the corpus or data/lessons/overrides.json. */\n' +
    'window.LIRAASA_LEARN = ' +
    JSON.stringify(payload) +
    ';\n';
  writeFileSync(`${OUT_DIR}/learn-data.js`, js, 'utf8');
  console.log(
    `learn-core.js and learn-data.js (${String(Math.round(js.length / 1024))} KB, ${String(Object.keys(audioFiles).length)} audio files) → ${OUT_DIR}/`,
  );
}

void main();
