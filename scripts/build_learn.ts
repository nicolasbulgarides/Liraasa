/**
 * Build what the songbook editor's Learn view loads (ADR-0015):
 *
 *   editor/learn/learn-core.js   src/core/learn bundled as one classic script,
 *                                window.LiraasaLearn, so the editor still
 *                                opens from file:// with no module loader
 *   editor/learn/learn-data.js   window.LIRAASA_LEARN: the lexicon, the
 *                                validated corpus, the names, the author's
 *                                overrides, and the previous edition's
 *                                snapshot for the "What changed" lesson
 *
 *   npm run build:learn
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, URL } from 'node:url';
import { build } from 'vite';
import { buildLearnData, snapshotEdition } from '../src/core/learn';
import type { IdMapFile } from '../src/core/model/ids';
import type { RawLexicon } from '../src/core/model/raw';
import { loadLearnInput } from './learn_inputs';

/** The edition before the current one, for the "What changed" lesson. */
const PREVIOUS = 'data/lexicon/liraasa_1_1.json';
const IDS = 'data/lexicon/ids.json';

const OUT_DIR = 'editor/learn';

async function main(): Promise<void> {
  await build({
    configFile: false,
    logLevel: 'warn',
    resolve: {
      alias: { '@core': fileURLToPath(new URL('../src/core', import.meta.url)) },
    },
    build: {
      outDir: OUT_DIR,
      emptyOutDir: false,
      minify: false,
      sourcemap: false,
      target: 'es2020',
      lib: {
        entry: fileURLToPath(new URL('../src/core/learn/index.ts', import.meta.url)),
        name: 'LiraasaLearn',
        formats: ['iife'],
        fileName: () => 'learn-core.js',
      },
    },
  });

  const input = loadLearnInput();
  // 1.1 carries no inline ids: read it through the sidecar, as the 1.2 build did
  const previous = snapshotEdition(
    buildLearnData({
      lexicon: JSON.parse(readFileSync(PREVIOUS, 'utf8')) as RawLexicon,
      ids: JSON.parse(readFileSync(IDS, 'utf8')) as IdMapFile,
      // read with the same glosses as the current edition, so only real changes differ
      ...(input.pronounEnglish !== undefined ? { pronounEnglish: input.pronounEnglish } : {}),
    }),
  );
  const payload = {
    lexicon: input.lexicon,
    corpus: input.corpus,
    names: input.names,
    overrides: input.overrides,
    pronounEnglish: input.pronounEnglish,
    previous,
  };
  const js =
    '/* Generated by npm run build:learn. Do not edit: edit the lexicon, the corpus or data/lessons/overrides.json. */\n' +
    'window.LIRAASA_LEARN = ' +
    JSON.stringify(payload) +
    ';\n';
  writeFileSync(`${OUT_DIR}/learn-data.js`, js, 'utf8');
  console.log(
    `learn-core.js and learn-data.js (${String(Math.round(js.length / 1024))} KB) → ${OUT_DIR}/`,
  );
}

void main();
