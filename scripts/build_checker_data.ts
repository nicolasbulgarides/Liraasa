/**
 * CLI: wrap the grammar checker's data for the browser.
 *
 *   npm run build:checker
 *
 * The editor opens straight from disk (file://), where a page cannot fetch a
 * JSON file, so each data file is written as a script that assigns it to a
 * global. The content is the JSON itself, unchanged:
 *
 *   editor/checker/data/reference.js  window.LIRAASA_REF          handoff/liraasa_2_2_llm.json
 *   editor/checker/data/extra.js      window.LIRAASA_CHECKER_EXTRA legacy spellings + names
 *   editor/checker/data/flags.js      window.LIRAASA_FLAGS        data/checker/lexicon_flags.json
 *   editor/checker/data/english.js    window.LIRAASA_ENGLISH      data/checker/english.json + calques.json
 *
 * The LLM JSON is the source of truth for words and rules. Two things the
 * checker's reader needs are not in it and come from the lexicon instead:
 * the older spellings (reader step "a legacy spelling → warn"), each with the
 * edition that retired it when a changeset in data/changes records that
 * (2.1:G58; none recorded means pre-1.0), and the attested personal names
 * (data/checker/names.json).
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const REFERENCE = 'handoff/liraasa_2_2_llm.json';
const LEXICON = 'data/lexicon/liraasa_2_2.json';
const NAMES = 'data/checker/names.json';
const FLAGS = 'data/checker/lexicon_flags.json';
const ENGLISH = 'data/checker/english.json';
const CALQUES = 'data/checker/calques.json';
const OUT_DIR = 'editor/checker/data';
const CHANGES = 'data/changes';

interface Migration {
  to: string;
  kind: string;
  via?: string;
}

/**
 * From the changesets' ops: the edition each root was respelled in, by its old
 * spelling (`out`), and the edition a respelled spelling came in, by that
 * spelling (`introduced`: puzu came in 2.1 and left in 2.2).
 */
function respelledIn(): { out: Map<string, string>; introduced: Map<string, string> } {
  const out = new Map<string, string>();
  const introduced = new Map<string, string>();
  for (const f of readdirSync(resolve(CHANGES))
    .filter((x) => x.endsWith('.json'))
    .sort()) {
    const cs = JSON.parse(readFileSync(resolve(CHANGES, f), 'utf8')) as {
      edition?: string;
      ops?: { op: string; from: string | null; to: string | null }[];
    };
    for (const op of cs.ops ?? []) {
      if ((op.op === 'respell_root' || op.op === 'respell_as_compound') && op.from !== null) {
        out.set(op.from, cs.edition ?? '');
        if (op.op === 'respell_root' && op.to !== null) introduced.set(op.to, cs.edition ?? '');
      }
    }
  }
  return { out, introduced };
}

function wrap(global: string, source: string, json: string): string {
  return `/* Generated by scripts/build_checker_data.ts from ${source}. Do not edit. */\nwindow.${global} = ${json};\n`;
}

function main(): void {
  mkdirSync(resolve(OUT_DIR), { recursive: true });

  const reference = readFileSync(resolve(REFERENCE), 'utf8');
  JSON.parse(reference); // fail loudly on a broken reference
  writeFileSync(
    resolve(OUT_DIR, 'reference.js'),
    wrap('LIRAASA_REF', REFERENCE, reference),
    'utf8',
  );

  const lex = JSON.parse(readFileSync(resolve(LEXICON), 'utf8')) as {
    version: string;
    legacy: { migration_forms: Record<string, Migration> };
  };
  const names = (JSON.parse(readFileSync(resolve(NAMES), 'utf8')) as { names: string[] }).names;
  const { out: editions, introduced } = respelledIn();
  const extra = {
    version: lex.version,
    legacy: Object.fromEntries(
      Object.entries(lex.legacy.migration_forms).map(([old, m]) => {
        const edition = editions.get(m.via ?? '');
        const since = introduced.get(m.via ?? '');
        return [
          old,
          { to: m.to, kind: m.kind, ...(edition ? { edition } : {}), ...(since ? { since } : {}) },
        ];
      }),
    ),
    names,
  };
  writeFileSync(
    resolve(OUT_DIR, 'extra.js'),
    wrap('LIRAASA_CHECKER_EXTRA', `${LEXICON} (legacy) and ${NAMES}`, JSON.stringify(extra)),
    'utf8',
  );

  const english = {
    ...(JSON.parse(readFileSync(resolve(ENGLISH), 'utf8')) as Record<string, unknown>),
    calques: (JSON.parse(readFileSync(resolve(CALQUES), 'utf8')) as { calques: unknown[] }).calques,
  };
  writeFileSync(
    resolve(OUT_DIR, 'english.js'),
    wrap('LIRAASA_ENGLISH', `${ENGLISH} and ${CALQUES}`, JSON.stringify(english)),
    'utf8',
  );

  const flags = existsSync(resolve(FLAGS)) ? readFileSync(resolve(FLAGS), 'utf8') : '{}';
  writeFileSync(resolve(OUT_DIR, 'flags.js'), wrap('LIRAASA_FLAGS', FLAGS, flags), 'utf8');

  console.log(`wrote ${OUT_DIR}/reference.js, extra.js, flags.js, english.js`);
  console.log(
    `  ${String(Object.keys(extra.legacy).length)} legacy spellings, ${String(names.length)} names`,
  );
}

main();
