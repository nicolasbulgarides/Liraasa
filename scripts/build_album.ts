/**
 * CLI: read the album against the live lexicon (2.2:G68, ADR-0018, ADR-0019).
 *
 *   npx tsx scripts/build_album.ts
 *
 * The album (data/corpus/album_2_0) is canon 2.0 text, read with 2.0
 * spellings (2.1:G58). Its `recorded` lines are never edited. This computes
 * each line's spelling in the current edition from the live lexicon (the
 * respellings since 2.0, as legacy.migration_forms records them, through the
 * same `correctText` every migration uses), compares it with the 2.2 patch's
 * precomputed `spelling_2_2`, and halts unless every line that differs is one
 * the 2.3 patch lists in `album_read_today`, spelled as it lists it. It writes
 * data/corpus/album_2_0/album_current.json: every line with its current
 * spelling (null when unchanged) and the album readings (AR-…) placed on
 * their lines.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { correctText } from '../src/core/change/respell';
import type { RawLexicon } from '../src/core/model/raw';

const LEXICON = 'data/lexicon/liraasa_3_3.json';
const PATCH_2_3 = 'data/proposals/liraasa_2_3_patch.json';
const BEFORE = 'data/lexicon/liraasa_2_0.json';
const CORPUS = 'data/corpus/album_2_0/liraasa_album_corpus.json';
const READINGS = 'data/corpus/album_2_0/album_readings.json';
const OUT = 'data/corpus/album_2_0/album_current.json';

export interface AlbumLine {
  n: number;
  recorded: string;
  spelling_2_2: string | null;
}
export interface AlbumSong {
  track: string;
  title: string;
  lines: AlbumLine[];
}
export interface AlbumReading {
  id: string;
  track: string;
  line: number;
  recorded: string;
  confidence: 'certain' | 'author_confirm';
  issue: string;
  standard_form: string | null;
  note: string | null;
}

const load = (p: string): unknown => JSON.parse(readFileSync(p, 'utf8'));

/** Old spelling → current, for every respelling made since 2.0. */
export function since20(now: RawLexicon, before: RawLexicon): Record<string, string> {
  const old = before.legacy.migration_forms;
  return Object.fromEntries(
    Object.entries(now.legacy.migration_forms)
      .filter(([k]) => !(k in old))
      .map(([k, m]) => [k, m.to]),
  );
}

function main(): void {
  const lex = load(LEXICON) as RawLexicon;
  const mapping = since20(lex, load(BEFORE) as RawLexicon);
  const { songs } = load(CORPUS) as { songs: AlbumSong[] };
  const { readings } = load(READINGS) as { readings: AlbumReading[] };
  const differences: { track: string; line: number; patch: string | null; live: string | null }[] =
    [];
  const out = songs.map((s) => ({
    track: s.track,
    title: s.title,
    lines: s.lines.map((l) => {
      const r = correctText(l.recorded, mapping);
      const live = r.changed > 0 ? r.text : null;
      if (live !== l.spelling_2_2)
        differences.push({ track: s.track, line: l.n, patch: l.spelling_2_2, live });
      const reading = readings.find((x) => x.track === s.track && x.line === l.n);
      if (reading !== undefined && reading.recorded !== l.recorded)
        throw new Error(`${reading.id}: not the recorded text of ${s.track}:${String(l.n)}`);
      return {
        n: l.n,
        recorded: l.recorded,
        current: live,
        ...(reading ? { reading: reading.id } : {}),
      };
    }),
  }));
  const placed = new Set(
    out.flatMap((s) => s.lines.flatMap((l) => (l.reading ? [l.reading] : []))),
  );
  for (const r of readings) if (!placed.has(r.id)) throw new Error(`${r.id}: no such line`);
  // what 2.3 respells: exactly the lines the 2.3 patch lists, as it spells them (2.3:G69)
  const { album_read_today: listed } = load(PATCH_2_3) as {
    album_read_today: { track: string; line: number; current_after_patch: string }[];
  };
  const unlisted = differences.filter(
    (d) =>
      !listed.some(
        (x) => x.track === d.track && x.line === d.line && x.current_after_patch === d.live,
      ),
  );
  if (unlisted.length > 0 || differences.length !== listed.length)
    throw new Error(
      `${String(unlisted.length)} lines respelled since 2.2 that the 2.3 patch does not list as built ` +
        `(${String(differences.length)} respelled, ${String(listed.length)} listed)`,
    );
  writeFileSync(
    OUT,
    `${JSON.stringify(
      {
        about: `The album read against ${lex.version}: \`current\` is a line's ${lex.version} spelling where it differs from the recording (2.1:G58). Generated by scripts/build_album.ts; never edit.`,
        lexicon: LEXICON,
        lines: out.reduce((n, s) => n + s.lines.length, 0),
        respelled_since_2_2: differences,
        songs: out,
      },
      null,
      1,
    )}\n`,
    'utf8',
  );
  console.log(
    `${String(out.length)} tracks, ${String(readings.length)} readings placed; ` +
      `${String(differences.length)} lines respelled since 2.2, each as the 2.3 patch lists it`,
  );
  for (const d of differences)
    console.log(
      `  ${d.track}:${String(d.line)}  2.2 ${String(d.patch)}\n          now ${String(d.live)}`,
    );
}

if (process.argv[1]?.endsWith('build_album.ts')) main();
