/**
 * CLI: the data the strict checker derives from the language itself (2.5).
 *
 *   npx tsx scripts/build_grammar_data.ts
 *
 * Writes:
 *   data/checker/transitive_2_5.json   every verb attested with an object in
 *                                      the canonical sentences, recipes and
 *                                      living ruling examples (2.5:G110: gome
 *                                      may passivise exactly these)
 *   data/checker/drafts_2_5.json       DRAFTS for the author, never final until
 *                                      approved: the change-of-state verbs
 *                                      (2.5:G110) and the verbs whose meaning has
 *                                      a recipient (2.5:G112), found by gloss
 *
 * The drafts are also written into review/questions_2_5.md for approval.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createChecker } from '../src/core/grammar';
import type { Clause } from '../src/core/grammar';
import { loadGrammarSource } from './grammar_source';

const OUT_TRANSITIVE = 'data/checker/transitive_2_5.json';
const OUT_DRAFTS = 'data/checker/drafts_2_5.json';

/** English heads of a change-of-state meaning (2.5:G110 names open, close, break, lose, fill, melt, burn, grow, change). */
const CHANGE =
  /^to (open|close|shut|break|shatter|crack|lose|fill|empty|melt|freeze|burn|grow|change|turn|dry|wet|sink|rise|fall|bend|tear|split|spill|boil|cool|warm|heat|fade|darken|brighten|wake|awaken|end|begin|start|stop|move|roll|spin|bloom|wither|rot|heal|harden|soften|thicken|widen|narrow|shrink|swell|ripen|fill up|light up|go out)\b/;
/** English heads of a meaning with a recipient (2.5:G112 names giving, lending, sending, owing, paying, bringing, teaching, showing, telling, singing to). */
const RECIPIENT =
  /^to (give|lend|send|owe|pay|bring|teach|show|tell|sing|offer|sell|hand|grant|gift|award|deliver|return something|read|write|whisper|promise|feed|serve|pour|throw|pass)\b/;

function main(): void {
  const src = loadGrammarSource();
  const ck = createChecker({ ...src, transitive: [] });
  const ref = src.ref as unknown as {
    examples: { sentences: [string, string][] };
    recipes: { liraasa: string }[];
    rulings: { status?: string; examples?: { liraasa: string }[] }[];
  };
  const lines = [
    ...ref.examples.sentences.map(([l]) => l),
    ...ref.recipes.map((r) => r.liraasa),
    // the function words' own examples are data too
    ...(
      ref as unknown as { small_words: { function_words: { rows: (string | null)[][] } } }
    ).small_words.function_words.rows
      .map((r) => String(r[3] ?? ''))
      .filter((l) => l !== '' && l !== 'null'),
    ...ref.rulings
      .filter((r) => !String(r.status ?? '').includes('SUPERSEDED by'))
      .flatMap((r) => (r.examples ?? []).map((e) => e.liraasa)),
  ];
  const transitive = new Map<string, string>();
  const visit = (c: Clause, tokens: { word?: { lower: string } }[], line: string): void => {
    const v = c.innerVerb ?? c.verb;
    if (
      v !== null &&
      (c.object !== null || c.objectClause !== null) &&
      (c.predKind === 'verb' || c.predKind === 'valency')
    ) {
      const form = (tokens[v]?.word?.lower ?? '').replace(/^(va|du|taro|yave|revo)-/, '');
      if (form !== '' && !transitive.has(form)) transitive.set(form, line);
    }
    for (const s of c.subordinates) visit(s, tokens, line);
    for (const a of c.adjuncts) if (a.clause !== null) visit(a.clause, tokens, line);
  };
  for (const line of lines) {
    const r = ck.checkLine(line);
    for (const s of r.sentences) for (const c of s.clauses) visit(c, s.tokens, line);
  }
  writeFileSync(
    resolve(OUT_TRANSITIVE),
    `${JSON.stringify(
      {
        about:
          'Verbs attested with an object in the 2.5 canonical sentences, recipes, function-word examples and living ruling examples, with the first line that shows it. 2.5:G110: gome may passivise exactly these. Generated by scripts/build_grammar_data.ts; do not edit.',
        verbs: [...transitive.keys()].sort(),
        attested_in: Object.fromEntries([...transitive].sort()),
      },
      null,
      1,
    )}\n`,
    'utf8',
  );

  // drafts from the dictionary's verb glosses
  const change: Record<string, string> = {};
  const recipient: Record<string, string> = {};
  for (const h of ck.index.headwords.values()) {
    const v = h.roles.v;
    if (v === undefined || h.image) continue;
    const senses = v.gloss.split(/;\s*/).map((x) => x.trim().toLowerCase());
    if (senses.some((x) => CHANGE.test(x))) change[v.form] = v.gloss;
    if (senses.some((x) => RECIPIENT.test(x)) || v.form in src.flags.give_type)
      recipient[v.form] = v.gloss;
  }
  for (const must of ['lallela', 'momvima']) {
    const forms = ck.index.forms.get(must) ?? [];
    const verb = forms.find((x) => x.pos === 'verb');
    if (verb !== undefined) change[must] = verb.gloss;
  }
  writeFileSync(
    resolve(OUT_DRAFTS),
    `${JSON.stringify(
      {
        about:
          'DRAFTS for the author (2.5 patch, author_inputs_needed). Not final until approved; the checker reports a construction that depends on them as unruled. Found by verb gloss by scripts/build_grammar_data.ts.',
        change_of_state_verbs: { ruling: '2.5:G110', item: 'I-22', status: 'draft', verbs: change },
        recipient_verbs: {
          ruling: '2.5:G112',
          item: 'I-38',
          status: 'draft',
          approved_already: Object.keys(src.flags.give_type).filter((k) => k !== '_about'),
          verbs: recipient,
        },
      },
      null,
      1,
    )}\n`,
    'utf8',
  );
  console.log(`wrote ${OUT_TRANSITIVE}: ${String(transitive.size)} verbs attested with an object`);
  console.log(
    `wrote ${OUT_DRAFTS}: ${String(Object.keys(change).length)} change-of-state, ${String(Object.keys(recipient).length)} recipient verbs (drafts)`,
  );
}

main();
