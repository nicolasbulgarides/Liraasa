/**
 * Build the 1.1 lexicon from the immutable 1.0 baseline plus the vocabulary
 * proposal.
 *
 * Rules this function is built to keep, from the integration prompt:
 *
 *  - **No grammar changes.** `phonology`, `morphology`, `motion_prefixes`,
 *    `grammar`, `function_words`, `pronouns`, `correlatives`, `numbers`,
 *    `time_and_dates`, `colors`, `discourse_particles`, `rulings_1_0`,
 *    `rulings_0_8_carried` and the existing `examples` are passed through by
 *    reference and never rebuilt.
 *  - **1.0 entries are untouched**, byte-for-byte in parsed content.
 *  - **Seven forms are generated by the unchanged 1.0 rule**, not copied from
 *    the proposal, so a bad proposed spelling cannot slip through.
 *  - **Insertion follows `safe_integration_order`**, so a component always
 *    exists before the compound that uses it.
 *
 * The result is deterministic: the same inputs give byte-identical output.
 */
import { SLOT_RAW_KEY, FORM_SLOTS } from '../config/slots';
import { sevenForms } from '../morphology/sevenForms';
import type { RawHeadword, RawLexicon, RawSlots } from '../model/raw';
import { decisionFor } from './decisions';
import { deriveSynonyms } from './synonyms';
import { isCompound, type Proposal, type ProposedEntry } from './proposalTypes';

export interface IntegrationOptions {
  /** The edition being produced. */
  version: string;
  /** ISO 8601 UTC build stamp. Supplied, not read from the clock, so runs are reproducible. */
  builtUtc: string;
  /** sha256 of the 1.0 baseline, recorded in the output. */
  baselineSha256: string;
  /** Examples to append. Existing examples are never touched. */
  newExamples?: readonly Record<string, unknown>[];
}

export interface IntegrationRecord {
  headword: string;
  type: 'Primal' | 'Compound';
  components: string[] | null;
  domain: string;
  gloss: string;
  /** `accepted` or `narrowed`; rejections never reach the output. */
  outcome: 'accepted' | 'narrowed';
  originalGloss?: string;
  reason?: string;
}

export interface IntegrationResult {
  lexicon: RawLexicon;
  added: IntegrationRecord[];
  rejected: { headword: string; reason: string }[];
  /** Proposed spellings the generator disagreed with. Fatal if non-empty. */
  formDisagreements: string[];
}

export class IntegrationError extends Error {}

/** Build a seven-slot block in the canonical raw key order. */
function rawSlotsFrom(values: Record<string, string>): RawSlots {
  const out: Record<string, string> = {};
  for (const slot of FORM_SLOTS) out[SLOT_RAW_KEY[slot]] = values[slot] ?? '';
  return out as unknown as RawSlots;
}

/**
 * The editorial trail for a new entry, as `notes`.
 *
 * Carries the semantic scope the proposal supplied, any narrowing applied, and
 * the ELEVATED risk flag, so the reasoning travels with the data.
 */
function buildNotes(entry: ProposedEntry): string {
  const parts: string[] = ['Added in 1.1 (vocabulary-only supplement).'];

  const scope = isCompound(entry) ? entry.meaning_scope : entry.semantic_scope;
  if (scope.length > 0) parts.push(`Scope: ${scope}`);

  if (isCompound(entry)) {
    parts.push(`Components: ${entry.components.join(' + ')}.`);
    if (entry.semantic_risk === 'ELEVATED') {
      parts.push('Lexicalised metaphor: read the scope, not the parts, for its meaning.');
    }
    if (entry.overlap_warning !== undefined) parts.push(`Overlap: ${entry.overlap_warning}`);
  }

  const decision = decisionFor(entry.headword);
  if (decision?.kind === 'narrow') {
    parts.push(`Gloss narrowed on integration: ${decision.reason}`);
  }

  // The scope notes come from the proposal and do not all end in a stop, so
  // give each part one before joining.
  return parts.map((p) => (/[.!?]$/.test(p) ? p : `${p}.`)).join(' ');
}

/**
 * Build one new headword.
 *
 * Forms come from the generator, never from the proposal. The root gloss may be
 * replaced by a narrowing decision; the other six slots are taken as proposed,
 * with anything unused left exactly `"— (unused)"`.
 */
function buildHeadword(entry: ProposedEntry, version: string): RawHeadword {
  const generated = sevenForms(entry.headword);
  const decision = decisionFor(entry.headword);

  const glossValues: Record<string, string> = {};
  for (const slot of FORM_SLOTS) {
    const proposed = (entry.proposed_glosses as unknown as Record<string, string>)[
      SLOT_RAW_KEY[slot]
    ];
    glossValues[slot] = proposed ?? '— (unused)';
  }
  if (decision?.kind === 'narrow' && decision.gloss !== undefined) {
    glossValues.root = decision.gloss;
  }

  const glosses = rawSlotsFrom(glossValues);

  /*
   * Key order mirrors a 1.0 headword exactly, and both status fields are
   * written:
   *
   *   status_1_0: 'NEW'  — required by check 9 of the author's unmodified
   *                        validate.py, and true in the sense the field
   *                        carries: this entry is new material, not carried
   *                        forward. Keeping it means the shipped validator
   *                        genuinely tests the new roots in checks 5 and 18
   *                        instead of skipping them (ADR-0009).
   *   status_1_1: 'NEW'  — the edition-specific record the proposal uses.
   *
   * `since: '1.1'` is the unambiguous discriminator for anything that needs to
   * tell a 1.1 addition from a 1.0 one.
   */
  return {
    root: entry.headword,
    type: entry.type,
    components: isCompound(entry) ? [...entry.components] : null,
    forms: rawSlotsFrom(generated),
    glosses,
    register: entry.register,
    domain: entry.domain,
    english_synonyms: deriveSynonyms(glosses),
    status_1_0: 'NEW',
    status_1_1: 'NEW',
    since: version,
    history_0_8: null,
    notes: buildNotes(entry),
    protected: true,
  } as unknown as RawHeadword;
}

export function integrate(
  baseline: RawLexicon,
  proposal: Proposal,
  options: IntegrationOptions,
): IntegrationResult {
  if (proposal.source_lexicon_sha256 !== options.baselineSha256) {
    throw new IntegrationError(
      `proposal targets ${proposal.source_lexicon_sha256}, baseline is ${options.baselineSha256}`,
    );
  }

  const byHeadword = new Map<string, ProposedEntry>(
    [...proposal.root_candidates, ...proposal.compound_candidates].map((c) => [c.headword, c]),
  );

  if (byHeadword.size !== proposal.safe_integration_order.length) {
    throw new IntegrationError(
      `${String(byHeadword.size)} candidates but ${String(proposal.safe_integration_order.length)} in safe_integration_order`,
    );
  }

  const existing = new Set(baseline.headwords.map((h) => h.root));
  const added: IntegrationRecord[] = [];
  const rejected: { headword: string; reason: string }[] = [];
  const formDisagreements: string[] = [];
  const newHeadwords: RawHeadword[] = [];

  for (const headword of proposal.safe_integration_order) {
    const entry = byHeadword.get(headword);
    if (entry === undefined) {
      throw new IntegrationError(`${headword} is in safe_integration_order but not a candidate`);
    }

    const decision = decisionFor(headword);
    if (decision?.kind === 'reject') {
      rejected.push({ headword, reason: decision.reason });
      continue;
    }

    if (existing.has(headword)) {
      rejected.push({ headword, reason: 'already an active 1.0 headword' });
      continue;
    }

    // A component must already exist: 1.0, or added earlier in this loop.
    if (isCompound(entry)) {
      for (const component of entry.components) {
        if (!existing.has(component)) {
          throw new IntegrationError(
            `${headword}: component ${component} is not an active headword at its point of insertion`,
          );
        }
      }
      if (entry.components.join('') !== headword) {
        throw new IntegrationError(
          `${headword}: spelling is not its components concatenated (${entry.components.join('+')})`,
        );
      }
    }

    // The generator is authoritative; a disagreement is a fatal data problem.
    const generated = sevenForms(headword);
    for (const slot of FORM_SLOTS) {
      const proposed = (entry.proposed_forms as unknown as Record<string, string>)[
        SLOT_RAW_KEY[slot]
      ];
      if (proposed !== generated[slot]) {
        formDisagreements.push(
          `${headword}.${slot}: proposed ${String(proposed)} != rule ${generated[slot]}`,
        );
      }
    }

    newHeadwords.push(buildHeadword(entry, options.version));
    existing.add(headword);

    added.push({
      headword,
      type: entry.type,
      components: isCompound(entry) ? [...entry.components] : null,
      domain: entry.domain,
      gloss: decision?.gloss ?? entry.english_gloss,
      outcome: decision?.kind === 'narrow' ? 'narrowed' : 'accepted',
      ...(decision?.kind === 'narrow'
        ? { originalGloss: entry.english_gloss, reason: decision.reason }
        : {}),
    });
  }

  if (formDisagreements.length > 0) {
    throw new IntegrationError(
      `the 1.0 verb rule disagrees with ${String(formDisagreements.length)} proposed spelling(s):\n  ${formDisagreements.slice(0, 10).join('\n  ')}`,
    );
  }

  // Headwords stay in the author's order: 1.0 verbatim, then the new material
  // in dependency order. Existing objects are reused by reference.
  const headwords = [...baseline.headwords, ...newHeadwords];

  const examples =
    options.newExamples === undefined
      ? baseline.examples
      : [...baseline.examples, ...(options.newExamples as RawLexicon['examples'])];

  // Everything not listed here is passed through untouched, grammar included.
  const lexicon: RawLexicon = {
    ...baseline,
    version: options.version,
    built_utc: options.builtUtc,
    source: `Built deterministically from liraasa_1_0.json (sha256 ${options.baselineSha256}) by scripts/integrate.ts using the 1.1 vocabulary proposal. Vocabulary-only supplement: no grammar, phonology, morphology, particle, pronoun or ruling was changed. This JSON is the single source of truth for Liraasa ${options.version}.`,
    headwords,
    examples,
  };

  return { lexicon, added, rejected, formDisagreements };
}
