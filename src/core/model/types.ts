/**
 * The internal model. Typed, camelCase, edition-agnostic.
 *
 * Every record keeps a reference to the raw object it came from, held
 * non-enumerably under `RAW` so it never reaches `JSON.stringify` or a
 * structural equality assertion (ADR-0002).
 */
import type { EntryRegister } from '../config/registers';
import type { FormSlot } from '../config/slots';
import type { Forms } from '../morphology/sevenForms';
import type {
  RawColor,
  RawCorrelative,
  RawDiscourseParticle,
  RawExample,
  RawFunctionWord,
  RawHeadword,
  RawLexicon,
  RawPronoun,
  RawTimeWord,
} from './raw';

/** The symbol under which a record carries its source object. */
export const RAW = Symbol('raw');

export interface WithRaw<R> {
  readonly [RAW]: R;
}

/** Attach a raw object non-enumerably. */
export function attachRaw<T extends object, R>(value: T, raw: R): T & WithRaw<R> {
  Object.defineProperty(value, RAW, { value: raw, enumerable: false, writable: false });
  return value as T & WithRaw<R>;
}

export type EntryId = string;

export type HeadwordType = 'primal' | 'compound';

export type HeadwordStatus = 'carried' | 'new' | 'replaced' | 'redefined' | 'rewritten' | 'merged';

export type Glosses = Record<FormSlot, string>;

export interface History08 {
  status: string;
  editorialNote: string;
}

export interface Headword extends WithRaw<RawHeadword> {
  id: EntryId;
  /** The headword spelling. Changes on a respell; the id does not. */
  spelling: string;
  type: HeadwordType;
  /** `[modifier, head]` for a compound, `null` for a primal. */
  components: readonly [string, string] | null;
  forms: Forms;
  glosses: Glosses;
  register: EntryRegister;
  domain: string;
  englishSynonyms: readonly string[];
  status: HeadwordStatus;
  since: string;
  /** The 0.8 spelling this entry replaces, if any. */
  replaces?: string;
  history08: History08 | null;
  notes: string;
  /** `true` on every 1.0 headword: the spelling is never regenerated by rule. */
  protected: boolean;
}

export interface FunctionWord extends WithRaw<RawFunctionWord> {
  id: EntryId;
  form: string;
  meaning: string;
  position: string;
  example: string;
  exampleGloss: string;
  /** A clause-slot name on the 27 new in 1.0; `null` on the rest. */
  slotClass: string | null;
  status: string;
  since: string;
  notes?: string;
  examples?: readonly { liraasa: string; english: string }[];
  /** True when the form is more than one word and must not be tokenised whole. */
  isMultiWord: boolean;
}

export interface Pronoun extends WithRaw<RawPronoun> {
  id: EntryId;
  form: string;
  person: string;
  number: string;
  possessive: string;
  reflexive: string;
}

export interface Correlative extends WithRaw<RawCorrelative> {
  id: EntryId;
  form: string;
  determiner: string;
  concept: string;
  gloss: string;
}

export interface TimeWord extends WithRaw<RawTimeWord> {
  id: EntryId;
  form: string;
  english: string;
}

export interface Color extends WithRaw<RawColor> {
  id: EntryId;
  family: string;
  base: string;
  dark: string;
  life: string;
  gem: string;
  light: string;
  notes: string;
}

export interface DiscourseParticle extends WithRaw<RawDiscourseParticle> {
  id: EntryId;
  form: string;
  pragmaticFunction: string;
  positions: string;
  register: string;
  examples: readonly { liraasa: string; english: string }[];
}

export type ExampleStatus = 'carried' | 'new' | 'migrated' | 'historical' | 'formula';

export interface Example extends WithRaw<RawExample> {
  liraasa: string;
  english: string;
  feature: string;
  status: ExampleStatus;
  source: string;
  changes: readonly string[];
  /** `historical` examples are skipped by checks 14, 15 and 21. */
  isLive: boolean;
}

export interface Ruling {
  /** Edition-qualified, e.g. `1.0:G19` (ADR-0004). */
  ref: string;
  edition: string;
  localId: string;
  topic: string;
  ruling: string;
  /** What the ruling refines, as the data words it (1.2 on). */
  refines: readonly string[];
  /** Worked examples, `[liraasa, english]`, where the data gives them (1.2 on). */
  examples: readonly { liraasa: string; english: string }[];
}

export interface RhymeFamily {
  ending: string;
  members: readonly string[];
  count: number;
}

/**
 * How a pre-1.0 spelling maps forward (ruling 1.0:G19).
 *
 * `archived-phrase` is the case that breaks the "one spelling to one form"
 * assumption: five compounds were archived in favour of a multi-word phrase,
 * so `to` is not a single form and cannot be looked up in `byForm`.
 */
export type MigrationKind = 'retired' | 'respelled' | 'merged' | 'rewritten' | 'archived-phrase';

export interface MigrationForm {
  from: string;
  to: string;
  slot: string;
  via: string;
  kind: MigrationKind;
  /** True when `to` is a phrase rather than a single form. */
  isPhrase: boolean;
}

export interface ReservedSpelling {
  spelling: string;
  state: string;
  replacement: string;
  reusableFrom: string;
  whyReserved: string;
}

export interface SettledQuestion {
  question: string;
  answer: string;
}

/** The whole loaded lexicon, in internal form. */
/** The image-compound pattern of 2.0 (2.0:G40, ADR-0016). */
export interface ImageCompounds {
  ruling: string;
  rule: string;
  /** Modifier headword id → how it reads as a modifier. */
  modifiers: ReadonlyMap<EntryId, { asModifier: string; sense: string }>;
  /** Head headword id → its template. */
  heads: ReadonlyMap<EntryId, { template: string }>;
  /** The former headwords kept as attested instances, with their ids and glosses. */
  attested: readonly Headword[];
  /** Pairs that stay headwords as well, with why. */
  keptAsHeadwords: ReadonlyMap<EntryId, string>;
}

export interface Lexicon {
  language: string;
  version: string;
  builtUtc: string;
  source: string;
  headwords: readonly Headword[];
  /** The image-compound pattern, from 2.0 on; `null` before. */
  imageCompounds: ImageCompounds | null;
  /** Default readings of the productive derivations (2.0:G41); `null` before 2.0. */
  derivationDefaults: Readonly<Record<string, string>> | null;
  functionWords: readonly FunctionWord[];
  pronouns: readonly Pronoun[];
  correlatives: readonly Correlative[];
  timeWords: readonly TimeWord[];
  colors: readonly Color[];
  discourseParticles: readonly DiscourseParticle[];
  examples: readonly Example[];
  rulings: readonly Ruling[];
  rhymeFamilies: readonly RhymeFamily[];
  migrationForms: readonly MigrationForm[];
  soundLedger: readonly ReservedSpelling[];
  settledQuestions: readonly SettledQuestion[];
  /** Kept whole so export can reproduce the file (ADR-0002). */
  readonly [RAW]: RawLexicon;
}

/** Anything with a stable id. */
export type Entry =
  | Headword
  | FunctionWord
  | Pronoun
  | Correlative
  | TimeWord
  | Color
  | DiscourseParticle;
