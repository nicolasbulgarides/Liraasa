import js from '@eslint/js';
import reactHooks from 'eslint-plugin-react-hooks';
import globals from 'globals';
import tseslint from 'typescript-eslint';

/**
 * Import boundaries (ADR-0003), enforced on the written specifier so no module
 * resolver is needed. The layering is:
 *
 *   src/core     pure TypeScript. No DOM, no React, no storage, no I/O.
 *   src/storage  adapters. May use core types; never reaches into the UI.
 *   src/ui       the shell. Talks only to src/core and src/storage.
 *                A module under src/ui/modules never imports a sibling module.
 */
const FORBID_UI = ['@ui/**', '**/ui/**', '**/../ui', 'react', 'react-dom', 'react-dom/**'];
const FORBID_STORAGE = ['@storage/**', '**/storage/**', '**/../storage'];

export default tseslint.config(
  {
    ignores: [
      'dist',
      'coverage',
      'node_modules',
      'data/**',
      // Generated by `npm run build:editor`; 361 kB of lexicon data.
      'editor/liraasa-data.js',
      // The author's separate TTS experiment, with its own virtualenv.
      'liraasa_voice_lab/**',
    ],
  },

  js.configs.recommended,
  ...tseslint.configs.strictTypeChecked,
  ...tseslint.configs.stylisticTypeChecked,

  {
    files: ['**/*.{ts,tsx}'],
    languageOptions: {
      parserOptions: {
        projectService: true,
        tsconfigRootDir: import.meta.dirname,
      },
    },
    rules: {
      '@typescript-eslint/consistent-type-imports': 'error',
      '@typescript-eslint/no-unnecessary-condition': 'error',
      '@typescript-eslint/switch-exhaustiveness-check': 'error',
      'no-console': ['error', { allow: ['warn', 'error'] }],
      eqeqeq: ['error', 'always'],
      // A leading underscore marks a binding that exists only to be discarded,
      // such as the `id` dropped by a rest-destructure.
      '@typescript-eslint/no-unused-vars': [
        'error',
        {
          argsIgnorePattern: '^_',
          varsIgnorePattern: '^_',
          caughtErrorsIgnorePattern: '^_',
          ignoreRestSiblings: true,
        },
      ],
    },
  },

  // The core is pure logic: no UI, no storage, no DOM, no I/O.
  {
    files: ['src/core/**/*.ts'],
    languageOptions: { globals: {} },
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [
            {
              group: FORBID_UI,
              message: 'src/core is pure logic: it must not import the UI or React.',
            },
            {
              group: FORBID_STORAGE,
              message: 'src/core must not import src/storage; storage calls core, not the reverse.',
            },
            {
              group: ['node:*'],
              message:
                'src/core must not perform I/O. Inject a provider and keep the node calls in scripts/ or src/storage.',
            },
          ],
        },
      ],
      'no-restricted-globals': [
        'error',
        { name: 'window', message: 'src/core must not touch the DOM.' },
        { name: 'document', message: 'src/core must not touch the DOM.' },
        { name: 'localStorage', message: 'src/core must not touch browser storage.' },
        { name: 'indexedDB', message: 'src/core must not touch browser storage.' },
        { name: 'fetch', message: 'src/core must not perform I/O; inject a provider.' },
      ],
    },
  },

  // Storage adapters may use core, never the UI.
  {
    files: ['src/storage/**/*.ts'],
    languageOptions: { globals: globals.browser },
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [{ group: FORBID_UI, message: 'src/storage must not import the UI.' }],
        },
      ],
    },
  },

  {
    files: ['src/ui/**/*.{ts,tsx}'],
    languageOptions: { globals: globals.browser },
    plugins: { 'react-hooks': reactHooks },
    rules: reactHooks.configs.recommended.rules,
  },

  // One module never imports a sibling module; they meet in src/core.
  {
    files: ['src/ui/modules/**/*.{ts,tsx}'],
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [
            {
              group: ['../*/**', '@ui/modules/*/**'],
              message:
                'UI modules are independent: reach another module through src/core, not directly.',
            },
          ],
        },
      ],
    },
  },

  {
    files: ['scripts/**/*.ts', '*.config.ts', 'eslint.config.js'],
    languageOptions: { globals: globals.node },
    rules: { 'no-console': 'off' },
  },

  {
    files: ['**/*.test.ts', 'tests/**/*.ts'],
    languageOptions: { globals: globals.node },
    rules: { '@typescript-eslint/no-non-null-assertion': 'off' },
  },

  { files: ['eslint.config.js'], ...tseslint.configs.disableTypeChecked },
);
